/** Server-only metric. No root/web-safe barrel exports this parser or its loader. */
import { Parser, Language, type Node, type Tree } from 'web-tree-sitter';
import { fileURLToPath } from 'node:url';

export const CHANGE_SIZE_VERSION = 1;
/** Exact dependency pins; the manifest parity control guards upgrades. */
export const CHANGE_SIZE_DEPENDENCIES = {
  runtimeVersion: '0.25.10',
  grammarPackageVersion: '0.3.1',
} as const;
export const CHANGE_SIZE_LIMITS = {
  maxBytes: 1024 * 1024,
  maxUnits: 100_000,
  editBudget: 512,
  workBudget: 1_000_000,
  timeoutMicros: 250_000,
} as const;
export type LanguageName = 'python' | 'php' | 'typescript' | 'tsx' | 'javascript';
export interface FileTexts {
  path: string;
  base: string | Uint8Array | null;
  head: string | Uint8Array | null;
}
export interface UnitSize {
  added: number;
  deleted: number;
  net: number;
  churn: number;
  structuralChurn: number;
  approximate: boolean;
}
export interface ChangeSizeSet {
  version: number;
  touched: string[];
  excluded: string[];
  files: { path: string; size: UnitSize | null }[];
  total: UnitSize & { nullFiles: number };
}
export type ChangeSizeOptions = Partial<{ [K in keyof typeof CHANGE_SIZE_LIMITS]: number }>;
export type ChangeSizeCounter = (
  files: readonly FileTexts[],
  options?: ChangeSizeOptions,
) => ChangeSizeSet;
interface Unit {
  key: string;
  structural: string;
  row: number;
}
const EXTENSIONS: Record<string, LanguageName> = {
  py: 'python',
  php: 'php',
  module: 'php',
  inc: 'php',
  install: 'php',
  theme: 'php',
  profile: 'php',
  engine: 'php',
  ts: 'typescript',
  mts: 'typescript',
  cts: 'typescript',
  tsx: 'tsx',
  js: 'javascript',
  mjs: 'javascript',
  cjs: 'javascript',
  jsx: 'javascript',
};
export const changeSizeLanguage = (path: string): LanguageName | undefined =>
  EXTENSIONS[path.split('.').pop()?.toLowerCase() ?? ''];

export function excludedChangeSizePath(path: string): boolean {
  return (
    /(^|\/)(tests?|__tests__|specs?|__fixtures__|fixtures?|__snapshots__|e2e|cypress|playwright|docs?|generated|vendor|third_party|third-party|node_modules|dist|build|out|target|coverage|\.next|\.git|\.haive|\.haive-data|venv|\.venv|__pycache__|\.cache|\.turbo|\.nuxt|\.svelte-kit)(\/|$)/i.test(
      path,
    ) ||
    /(^|\/)(readme|changelog|license|notice|authors|contributing)(\.[^/]*)?$/i.test(path) ||
    /\.d\.[cm]?ts$/i.test(path) ||
    /(^|\/)(test_[^/]+\.py|[^/]+_test\.py|[^/]+Test\.php|[^/]+\.(test|spec)\.[cm]?[jt]sx?|[^/]+\.(generated|g)\.[^/]+|[^/]+\.min\.[^/]+|[^/]+\.lock|[^/]*lock[^/]*\.(yaml|json)|[^/]+\.(md|mdx|rst|adoc|map))$/i.test(
      path,
    )
  );
}

/** A generated marker must come from the base, or from a genuinely new file.
 * A marker added to existing implementation cannot hide that implementation's edits. */
function generatedHeader(input: FileTexts['base']): boolean {
  if (input === null) return false;
  const text =
    typeof input === 'string'
      ? input.slice(0, 2048)
      : new TextDecoder().decode(input.subarray(0, 2048));
  return /^(?:[ \t]*(?:\/\/|#|\/\*|\*)[^\n]*)(?:@generated|automatically generated|code generated|generated by)/im.test(
    text,
  );
}

/** Initialization alone may load trusted installed WASM; callers can instead supply bytes.
 * The returned calculation uses only its input and loaded grammars, with no filesystem IO. */
export async function initializeChangeSize(input?: {
  runtime: Uint8Array;
  grammars: Partial<Record<LanguageName, Uint8Array>>;
}): Promise<ChangeSizeCounter> {
  await Parser.init(input ? { wasmBinary: input.runtime } : undefined);
  const grammars: Partial<Record<LanguageName, Language>> = {};
  for (const name of ['python', 'php', 'typescript', 'tsx', 'javascript'] as const) {
    const source = input
      ? input.grammars[name]
      : fileURLToPath(
          import.meta.resolve(`@vscode/tree-sitter-wasm/wasm/tree-sitter-${name}.wasm`),
        );
    if (source) grammars[name] = await Language.load(source);
  }
  return createChangeSizeCounter(grammars);
}

