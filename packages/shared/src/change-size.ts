function literalKind(type: string): string {
  if (['true', 'false', 'boolean'].includes(type)) return 'boolean';
  if (['null', 'none'].includes(type)) return 'null';
  if (['integer', 'float', 'number'].includes(type)) return 'number';
  if (['string', 'encapsed_string', 'string_literal'].includes(type)) return 'string';
  return type;
}
function literalValue(node: Node, language: LanguageName): string {
  if (literalKind(node.type) === 'number') return node.text.replaceAll('_', '');
  if (literalKind(node.type) !== 'string') return node.text;
  // Quote delimiters are punctuation; preserve prefixes, escapes and content values.
  const match = /^([rubf]*)("""|'''|"|')([\s\S]*)\2$/i.exec(node.text);
  if (!match) return node.text;
  const prefix = match[1]!.toLowerCase();
  const content = match[3]!.replace(/\\([\\"'])/g, (escape, char: string) => {
    if (prefix.includes('r')) return escape;
    // PHP's quote escapes depend on which delimiter was used.
    if (language === 'php' && char !== '\\' && char !== match[2]) return escape;
    return char;
  });
  return `${prefix}:${content}`;
}
const INTERPOLATIONS = new Set([
  'interpolation',
  'template_substitution',
  'variable_name',
  'member_access_expression',
  'subscript_expression',
]);
const OPERATORS = /^(?:[-+*/%=<>!&|^~?]+|and|or|not|in|is|not in|is not|instanceof)$/;
function project(tree: Tree, maxUnits: number, language: LanguageName): Unit[] | null {
  if (tree.rootNode.hasError) return null;
  const units: Unit[] = [];
  // Iterative traversal also bounds deeply nested untrusted syntax without JS recursion.
  const stack: { node: Node; end?: boolean }[] = [{ node: tree.rootNode }];
  while (stack.length) {
    const { node, end } = stack.pop()!;
    if (end) units.push({ key: 'EndBlock', structural: 'EndBlock', row: node.endPosition.row });
    else {
      const type = node.type;
      if (type === 'comment' || type === 'php_tag' || type === 'text') continue;
      const name = NAMES.has(type);
      const literal = LITERALS.has(type);
      const composite =
        literal &&
        (type === 'template_string' ||
          node.namedChildren.some((c) => c !== null && INTERPOLATIONS.has(c.type)));
      const assignmentWrapper =
        type === 'expression_statement' &&
        ['assignment', 'augmented_assignment'].includes(node.firstNamedChild?.type ?? '');
      const count =
        name ||
        literal ||
        (!assignmentWrapper &&
          (type.endsWith('_statement') ||
            type.endsWith('_expression') ||
            type.endsWith('_declaration') ||
            EXPRESSIONS.has(type)) &&
          !BLOCKS.has(type));
      if (count) {
        const operators =
          name || literal
            ? []
            : node.children
                .filter((c): c is Node => c !== null && !c.isNamed && OPERATORS.test(c.text))
                .map((c) => c.text);
        const operator =
          type === 'comparison_operator' ? (operators[0] ?? '') : operators.join(' ');
        const structural = `${literal ? literalKind(type) : type}${operator ? ':' + operator : ''}`;
        units.push({
          key: name
            ? `${type}:${node.text}`
            : literal && !composite
              ? `${structural}:${literalValue(node, language)}`
              : structural,
          structural,
          row: node.startPosition.row,
        });
        // Python represents a comparison chain in one node; each comparison is one unit.
        if (type === 'comparison_operator')
          for (const op of operators.slice(1)) {
            const key = `${type}:${op}`;
            units.push({ key, structural: key, row: node.startPosition.row });
          }
      }
      // Names, PHP variables and string literals count once, without their grammar wrappers.
      if (!name && (!literal || composite)) {
        if (BLOCKS.has(type)) stack.push({ node, end: true });
        for (let i = node.namedChildCount - 1; i >= 0; i--)
          stack.push({ node: node.namedChild(i)! });
      }
    }
    if (units.length > maxUnits) return null;
  }
  return units;
}

/** Myers' furthest-reaching frontier: only the edit distance is needed for added/deleted.
 * Work and edit bounds cap both CPU and frontier memory. */
function distance(
  a: readonly string[],
  b: readonly string[],
  limits: Required<ChangeSizeOptions>,
): number | null {
  let start = 0,
    endA = a.length,
    endB = b.length;
  while (start < endA && start < endB && a[start] === b[start]) start++;
  while (endA > start && endB > start && a[endA - 1] === b[endB - 1]) {
    endA--;
    endB--;
  }
  const n = endA - start,
    m = endB - start;
  if (!n || !m) return n + m;
  let work = 0;
  const v = new Map<number, number>([[1, 0]]);
  for (let d = 0; d <= Math.min(n + m, limits.editBudget); d++) {
    for (let k = -d; k <= d; k += 2) {
      if (++work > limits.workBudget) return null;
      let x =
        k === -d || (k !== d && (v.get(k - 1) ?? -1) < (v.get(k + 1) ?? -1))
          ? (v.get(k + 1) ?? 0)
          : (v.get(k - 1) ?? 0) + 1;
      let y = x - k;
      while (x < n && y < m && a[start + x] === b[start + y]) {
        if (++work > limits.workBudget) return null;
        x++;
        y++;
      }
      v.set(k, x);
      if (x >= n && y >= m) return d;
    }
  }
  return null;
}

/** Monotone unique-line anchors retain equal lines; unmatched spans are replacements.
 * This is explicitly approximate, including when the line layout itself changed. */
function approximateDistance(a: Unit[], b: Unit[], structural: boolean): number {
  const lines = (units: Unit[]) => {
    const groups = new Map<number, string[]>();
    for (const u of units) {
      const group = groups.get(u.row) ?? [];
      group.push(structural ? u.structural : u.key);
      groups.set(u.row, group);
    }
    return [...groups.values()].map((keys) => ({ key: JSON.stringify(keys), count: keys.length }));
  };
  const left = lines(a),
    right = lines(b);
  const unique = (rows: typeof left) => {
    const out = new Map<string, number>();
    rows.forEach((r, i) => out.set(r.key, out.has(r.key) ? -1 : i));
    return out;
  };
  const la = unique(left),
    lb = unique(right);
  let last = -1,
    retained = 0;
  for (let i = 0; i < left.length; i++) {
    const row = left[i]!,
      j = lb.get(row.key);
    if (la.get(row.key) === i && j !== undefined && j > last) {
      retained += row.count;
      last = j;
    }
  }
  return a.length + b.length - 2 * retained;
}

export function createChangeSizeCounter(
  grammars: Partial<Record<LanguageName, Language>>,
): ChangeSizeCounter {
  return (files, options = {}) => {
    const limits = { ...CHANGE_SIZE_LIMITS, ...options };
    const result: ChangeSizeSet = {
      version: CHANGE_SIZE_VERSION,
      touched: files.map((f) => f.path),
      excluded: [],
      files: [],
      total: {
        added: 0,
        deleted: 0,
        net: 0,
        churn: 0,
        structuralChurn: 0,
        approximate: false,
        nullFiles: 0,
      },
    };
    for (const file of files) {
      if (
        excludedChangeSizePath(file.path) ||
        generatedHeader(
          file.base === '' || (file.base instanceof Uint8Array && file.base.length === 0)
            ? file.head
            : file.base,
        )
      ) {
        result.excluded.push(file.path);
        continue;
      }
      let size: UnitSize | null = null;
      const language = changeSizeLanguage(file.path);
      const grammar = language ? grammars[language] : undefined;
      if (grammar) {
        const parser = new Parser();
        const trees: Tree[] = [];
        try {
          parser.setLanguage(grammar);

          const parse = (input: FileTexts['base']) => {
            if (input === null) return null;
            const bytes = typeof input === 'string' ? new TextEncoder().encode(input) : input;
            if (bytes.length > limits.maxBytes) return null;
            const text = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
            if (text.includes('\0')) return null;
            parser.reset();
            const deadline = performance.now() + limits.timeoutMicros / 1000;
            const tree = parser.parse(text, null, {
              progressCallback: () => performance.now() >= deadline,
            });
            if (!tree) return null;
            trees.push(tree);
            return project(tree, limits.maxUnits, language!);
          };
          const a = parse(file.base),
            b = parse(file.head);
          if (a && b) {
            const exact = distance(
              a.map((u) => u.key),
              b.map((u) => u.key),
              limits,
            );
            const structural = distance(
              a.map((u) => u.structural),
              b.map((u) => u.structural),
              limits,
            );
            const churn = exact ?? approximateDistance(a, b, false);
            size = {
              added: (churn + b.length - a.length) / 2,
              deleted: (churn + a.length - b.length) / 2,
              net: b.length - a.length,
              churn,
              structuralChurn: structural ?? approximateDistance(a, b, true),
              approximate: exact === null || structural === null,
            };
          }
        } catch {
          /* Invalid UTF-8, parser failure or timeout is a coverage gap. */
        } finally {
          for (const tree of trees) tree.delete();
          parser.delete();
        }
      }
      result.files.push({ path: file.path, size });
      if (!size) result.total.nullFiles++;
      else {
        for (const key of ['added', 'deleted', 'net', 'churn', 'structuralChurn'] as const)
          result.total[key] += size[key];
        result.total.approximate ||= size.approximate;
      }
    }
    return result;
  };
}
