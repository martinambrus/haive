import { chownSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const modulesDir = join(root, 'modules');

const names = readdirSync(modulesDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => join(modulesDir, entry.name, 'package.json'))
  .flatMap((file) => {
    try {
      return [JSON.parse(readFileSync(file, 'utf8')).name];
    } catch (err) {
      if (err.code === 'ENOENT') return [];
      throw err;
    }
  })
  .sort();

const body = `// Generated by scripts/gen-modules.mjs. Do not edit.
export const moduleRegistry = ${names.length === 0 ? '[]' : JSON.stringify(names)} as const;
`;

for (const pkg of ['api', 'worker']) {
  const out = join(root, 'packages', pkg, 'src', 'modules.generated.ts');
  let current = null;
  try {
    current = readFileSync(out, 'utf8');
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
  }
  if (current === body) continue;
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, body);
  // The dev containers run this as root on the bind-mounted tree; hand the file back like build-libs.sh.
  if (process.getuid?.() === 0) {
    const { uid, gid } = statSync(root);
    chownSync(out, uid, gid);
  }
}
